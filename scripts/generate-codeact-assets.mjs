// Regenerates agent/lib/codeact/generated/assets.ts from installed packages:
// the Arquero browser bundle (evaluated inside QuickJS) and the Geist font
// (used to rasterize charts). Run after upgrading `arquero` or `geist`:
//
//   pnpm gen:codeact
//
// The assets are inlined so the agent bundle never depends on reading files
// from node_modules at runtime.
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

const readJson = (path) => JSON.parse(readFileSync(join(root, path), "utf8"));
const arqueroPackage = readJson("node_modules/arquero/package.json");
const arqueroSource = readFileSync(join(root, "node_modules/arquero/dist/arquero.min.js"), "utf8");
const geistPackage = readJson("node_modules/geist/package.json");
const geist = readFileSync(join(root, "node_modules/geist/dist/fonts/geist-sans/Geist-Regular.ttf"));

const sha = (value) => createHash("sha256").update(value).digest("hex").slice(0, 16);

const output = `// GENERATED by scripts/generate-codeact-assets.mjs — do not edit by hand.
// Arquero ${arqueroPackage.version} (BSD-3-Clause) browser bundle, sha256:${sha(arqueroSource)}
// Geist Regular from geist ${geistPackage.version} (SIL Open Font License 1.1), sha256:${sha(geist)}
/* eslint-disable */

export const ARQUERO_VERSION = ${JSON.stringify(arqueroPackage.version)};
export const ARQUERO_SOURCE_SHA = ${JSON.stringify(sha(arqueroSource))};
export const ARQUERO_SOURCE: string = ${JSON.stringify(arqueroSource)};

export const GEIST_REGULAR_SHA = ${JSON.stringify(sha(geist))};
export const GEIST_REGULAR_TTF_BASE64 = ${JSON.stringify(geist.toString("base64"))};
`;

const target = join(root, "agent/lib/codeact/generated/assets.ts");
mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, output);
console.log(`wrote ${target} (${Math.round(output.length / 1024)} KB)`);
